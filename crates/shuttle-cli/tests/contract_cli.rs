//! Binary-level CLI integration tests for `shuttle impact --contract` — the G6·S1
//! **semantic-truth** axis . Spawns
//! the REAL `shuttle` binary and drives the cross-language contract graph end-to-end
//! over a hermetic git repo:
//!
//!   * A changed IDL file (`.proto`) declares a message + a service RPC.
//!   * Two generated impl files (Go + TypeScript) each carry a codegen banner
//!     AND reference the bare node names — the ONLY thing that mints a
//!     `ContractDirected` (HIGH) cross-language edge.
//!
//! The iron contract under test (§7 「绝不瞎猜」 / red line #11): a node is a
//! cross-language hit ONLY when ≥2 distinct languages provably anchor it via
//! codegen. Same-name-without-codegen is never laundered into an edge — it is a
//! `stale-contract` degrade. A known-but-unparsed IDL dialect degrades to
//! `unknown-idl-dialect`. shuttle computes and hands off; it never lands (#11).
//! Exit is ALWAYS 0 (bad-flag-combo is the one hard `anyhow::bail!`): the JSON
//! `ContractImpact` envelope is the machine contract a caller routes on.
//!
//! Hermetic: scratch repos live under the OS temp root (honours TMPDIR). The
//! git-backed cases skip when a scratch `.git/config` cannot be created (some
//! sandboxes permit the `git` binary but block writes to `.git/config`).

use std::io::Write;
use std::process::Command;

fn shuttle_bin() -> &'static str {
    env!("CARGO_BIN_EXE_shuttle")
}

/// A bare `git --version` is not enough: some sandboxes permit the binary but
/// block writes to `.git/config`, in which case the git-backed cases below must
/// skip (the contract walk reads `git ls-files`, so it needs a real repo).
fn can_init_git() -> bool {
    let probe = scratch_dir("initprobe");
    let ok = Command::new("git")
        .args(["init", "-q", "--template="])
        .current_dir(&probe)
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
        && probe.join(".git").join("config").exists();
    let _ = std::fs::remove_dir_all(&probe);
    ok
}

fn scratch_dir(tag: &str) -> std::path::PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let dir = std::env::temp_dir().join(format!("shuttle_contract_it_{tag}_{nanos}"));
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn write(dir: &std::path::Path, name: &str, body: &str) {
    let p = dir.join(name);
    if let Some(parent) = p.parent() {
        std::fs::create_dir_all(parent).unwrap();
    }
    let mut f = std::fs::File::create(&p).unwrap();
    f.write_all(body.as_bytes()).unwrap();
}

fn git(dir: &std::path::Path, args: &[&str]) {
    let out = Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "git {:?} failed: {}",
        args,
        String::from_utf8_lossy(&out.stderr)
    );
}

fn git_seed(dir: &std::path::Path) {
    git(dir, &["init", "-q", "--template="]);
    git(dir, &["config", "user.email", "t@t"]);
    git(dir, &["config", "user.name", "t"]);
    git(dir, &["config", "commit.gpgsign", "false"]);
    git(dir, &["add", "-A"]);
    git(dir, &["commit", "-q", "-m", "seed"]);
}

/// Run `shuttle impact --contract --json --changed <idl...> --root <ws>` and parse
/// stdout as the `ContractImpact` JSON. Asserts exit 0 (the machine contract).
fn run_contract_json(ws: &std::path::Path, changed: &[&str]) -> serde_json::Value {
    let mut args: Vec<String> = vec![
        "impact".into(),
        "--contract".into(),
        "--json".into(),
        "--root".into(),
        ws.to_str().unwrap().into(),
        "--changed".into(),
    ];
    for c in changed {
        args.push((*c).into());
    }
    let out = Command::new(shuttle_bin())
        .args(&args)
        .output()
        .expect("spawn shuttle impact --contract");
    assert!(
        out.status.success(),
        "shuttle impact --contract exited non-zero: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    serde_json::from_str(&stdout)
        .unwrap_or_else(|e| panic!("stdout is not ContractImpact JSON: {e}\n---\n{stdout}"))
}

// --- Shared fixtures: mirror the shuttle-nav pure/e2e suite exactly so the CLI
// --- integration and the library adjudication stay in lockstep. ------------

const USER_PROTO: &str = "\
package user.api;
message GetUserRequest { string id = 1; }
service UserService {
  rpc GetUser (GetUserRequest) returns (GetUserRequest);
}
";
const GO_GEN: &str = "\
// Code generated by protoc-gen-go. DO NOT EDIT.
type GetUserRequest struct{}
type UserService interface{}
func GetUser(r *GetUserRequest) {}
";
const TS_GEN: &str = "\
// @generated by protoc-gen-ts_proto
export interface GetUserRequest {}
export interface UserService {}
export function GetUser(r: GetUserRequest) {}
";

/// The happy path: a changed `.proto` whose message + RPC are code-generated in
/// BOTH Go and TypeScript. Every declared node is a provable cross-language hit
/// spanning the two impl files; nothing degrades.
#[test]
fn contract_cross_language_json_hits_go_and_ts() {
    if !can_init_git() {
        return;
    }
    let ws = scratch_dir("xlang");
    write(&ws, "api/user.proto", USER_PROTO);
    write(&ws, "gen/user.pb.go", GO_GEN);
    write(&ws, "web/client.ts", TS_GEN);
    git_seed(&ws);

    let v = run_contract_json(&ws, &["api/user.proto"]);

    // Not degraded: every node anchors on ≥2 languages.
    assert_eq!(v["degraded"], serde_json::json!(false), "unexpected: {v}");
    assert!(
        v["stale"].as_array().unwrap().is_empty(),
        "no node should be stale: {v}"
    );
    assert!(
        v["one_sided"].as_array().unwrap().is_empty(),
        "no node should be one-sided: {v}"
    );
    assert!(
        v["unknown_dialects"].as_array().unwrap().is_empty(),
        "proto is a known dialect: {v}"
    );

    let hits = v["hits"].as_array().expect("hits array");
    assert!(!hits.is_empty(), "expected cross-language hits: {v}");
    // Both impl languages must appear among the anchoring files.
    let langs: std::collections::BTreeSet<&str> =
        hits.iter().map(|h| h["lang"].as_str().unwrap()).collect();
    assert!(langs.contains("go"), "missing go anchor: {v}");
    assert!(
        langs.contains("ts") || langs.contains("typescript"),
        "missing ts anchor: {v}"
    );
    // The message node must be one of the provable hits.
    let node_ids: std::collections::BTreeSet<&str> = hits
        .iter()
        .map(|h| h["node_id"].as_str().unwrap())
        .collect();
    assert!(
        node_ids.iter().any(|n| n.contains("GetUserRequest")),
        "GetUserRequest must be a cross-language hit: {v}"
    );
}

/// A4「跨语言口径不一」cure: two files carry the SAME bare name but NO codegen
/// banner — so there is no proof they were regenerated from this contract. The
/// walk must NOT mint an edge; the node degrades to `stale-contract`.
#[test]
fn contract_a4_same_name_no_codegen_is_stale_not_a_hit() {
    if !can_init_git() {
        return;
    }
    let ws = scratch_dir("a4stale");
    write(&ws, "api/user.proto", USER_PROTO);
    // Hand-written look-alikes: same identifiers, but no `Code generated` /
    // `@generated` banner anywhere.
    write(
        &ws,
        "srv/user.go",
        "package srv\ntype GetUserRequest struct{}\ntype UserService interface{}\nfunc GetUser(r *GetUserRequest) {}\n",
    );
    write(
        &ws,
        "app/user.ts",
        "export interface GetUserRequest {}\nexport interface UserService {}\nexport function GetUser(r: GetUserRequest) {}\n",
    );
    git_seed(&ws);

    let v = run_contract_json(&ws, &["api/user.proto"]);

    assert!(
        v["hits"].as_array().unwrap().is_empty(),
        "same-name-without-codegen must NOT be a hit: {v}"
    );
    assert_eq!(v["degraded"], serde_json::json!(true), "must degrade: {v}");
    let stale = v["stale"].as_array().expect("stale array");
    assert!(
        !stale.is_empty(),
        "the drifted contract nodes must be stale: {v}"
    );
    // A §7 note is surfaced, never a laundered green edge.
    assert!(
        !v["notes"].as_array().unwrap().is_empty(),
        "a degrade note must be surfaced: {v}"
    );
}

/// A known IDL family we do NOT yet parse must be recorded as
/// `unknown-idl-dialect` and degrade — not silently produce zero hits as if the
/// contract were empty. The text renderer must print the degrade banner.
#[test]
fn contract_unknown_dialect_degrades_text_mode() {
    if !can_init_git() {
        return;
    }
    let ws = scratch_dir("unknown");
    // `.fbs` (FlatBuffers) is a recognised IDL family we do NOT parse — the
    // clean `unknown-idl-dialect` degrade signal (§7). (proto/thrift/openapi/
    // graphql all parse now, so a still-unparsed family is what proves the
    // degrade path end-to-end.)
    write(
        &ws,
        "api/schema.fbs",
        "table Foo { x:int; }\ntable Bar { y:int; }\n",
    );
    git_seed(&ws);

    // Text mode (no --json): assert the degrade banner is printed and exit 0.
    let out = Command::new(shuttle_bin())
        .args([
            "impact",
            "--contract",
            "--root",
            ws.to_str().unwrap(),
            "--changed",
            "api/schema.fbs",
        ])
        .output()
        .expect("spawn shuttle impact --contract text");
    assert!(
        out.status.success(),
        "text-mode contract must exit 0: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.contains("degraded"),
        "unknown dialect must surface a degrade banner: {stdout}"
    );

    // JSON mode: the dialect is recorded, not guessed into hits.
    let v = run_contract_json(&ws, &["api/schema.fbs"]);
    assert_eq!(v["degraded"], serde_json::json!(true), "must degrade: {v}");
    assert!(
        v["hits"].as_array().unwrap().is_empty(),
        "an unparsed dialect yields no provable hits: {v}"
    );
    assert!(
        !v["unknown_dialects"].as_array().unwrap().is_empty(),
        "the dialect must be recorded: {v}"
    );
}

/// G6-4: a GraphQL SDL contract (a dialect that only became parseable in G6-4)
/// mints the same provable cross-language edges as proto — proving the new
/// dialect flows end-to-end through the binary, not just the library. The
/// object type `User` is code-generated in BOTH Go and TS.
#[test]
fn contract_graphql_dialect_hits_cross_language() {
    if !can_init_git() {
        return;
    }
    let ws = scratch_dir("gql");
    write(
        &ws,
        "api/schema.graphql",
        "type Query {\n  getUser(id: ID!): User\n}\ntype User {\n  id: ID!\n  name: String\n}\n",
    );
    write(
        &ws,
        "gen/models_gen.go",
        "// Code generated by github.com/99designs/gqlgen. DO NOT EDIT.\ntype User struct{}\nfunc getUser() {}\n",
    );
    write(
        &ws,
        "web/graphql.ts",
        "// @generated by @graphql-codegen\nexport interface User {}\nexport function getUser() {}\n",
    );
    git_seed(&ws);

    let v = run_contract_json(&ws, &["api/schema.graphql"]);
    assert!(
        v["unknown_dialects"].as_array().unwrap().is_empty(),
        "graphql must be a KNOWN, parsed dialect now: {v}"
    );
    let hits = v["hits"].as_array().expect("hits array");
    let node_ids: std::collections::BTreeSet<&str> = hits
        .iter()
        .map(|h| h["node_id"].as_str().unwrap())
        .collect();
    assert!(
        node_ids.contains("User"),
        "the User object type must be a cross-language hit: {v}"
    );
    let langs: std::collections::BTreeSet<&str> =
        hits.iter().map(|h| h["lang"].as_str().unwrap()).collect();
    assert!(langs.contains("go"), "missing go anchor: {v}");
    assert!(
        langs.contains("ts") || langs.contains("typescript"),
        "missing ts anchor: {v}"
    );
}

/// The one hard failure the mode permits: `--contract` is a `--changed` mode and
/// must reject a `--base/--head` land-time combo (clap `conflicts_with_all`
/// already blocks `--changed` + `--base`, so we exercise the explicit bail).
#[test]
fn contract_rejects_base_head_combo() {
    // No git needed: the arg-combo guard fires before any repo read.
    let out = Command::new(shuttle_bin())
        .args(["impact", "--contract", "--base", "HEAD~1", "--head", "HEAD"])
        .output()
        .expect("spawn shuttle impact --contract bad-combo");
    assert!(
        !out.status.success(),
        "a base/head combo with --contract must be rejected"
    );
}
