//! Codegen anchoring (G6 · S1, continued): decide which *implementation* files
//! are provably generated from — and therefore bound to — each IDL contract
//! node. This is the ONLY basis on which a cross-language
//! [`crate::graph::EdgeKind::ContractDirected`] edge may be minted (§7 — never
//! guess). See /§2.4.
//!
//! The A4 病根 is treating two same-named symbols in different languages
//! (`Go helper()` vs `Python def helper`) as the same thing. The cure here is a
//! two-part *provable* test before any file anchors to a contract node:
//!
//! 1. **Codegen provenance.** The file carries an unmistakable generated-code
//!    banner ("Code generated by protoc", "Autogenerated by Thrift",
//!    "@generated", …). This is what proves the file was *produced from an IDL
//!    toolchain* rather than hand-written with a coincidental name.
//! 2. **Name reference.** The file references the contract node's declared name
//!    as a whole identifier token.
//!
//! A bare name match with no banner is a `NameMatch` coincidence, never an
//! anchor. A contract node anchored by ≥2 distinct languages is the provable
//! cross-language contract; one anchored by exactly one language is *one-sided*
//! (the counterpart side did not codegen — no cross-language edge); one
//! anchored by nobody, when it was just declared/changed, is a *stale contract*
//! (schema moved, codegen did not follow). Each degrade is recorded, never
//! papered over.

use crate::contract::{Contract, ContractKind, ContractSet};
use std::collections::{BTreeMap, BTreeSet};

/// Lower-cased generated-code banners. Presence of any one proves a file is an
/// IDL toolchain artifact (not a hand-written coincidence). We deliberately
/// keep this to well-known, unambiguous markers so that requiring one *plus* a
/// name reference makes the resulting anchor trustworthy — the whole point of
/// §7. Matched case-insensitively against the file's text.
const CODEGEN_MARKERS: &[&str] = &[
    "code generated by",
    "generated by the protocol buffer compiler",
    "autogenerated by thrift",
    "@generated",
    "do not edit",
    "this file is auto-generated",
    "auto-generated by",
];

/// One implementation file that provably codegens a contract node.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct AnchorFile {
    /// The generated source file's path.
    pub path: String,
    /// Its language id (via [`crate::lang_for_path`]).
    pub lang: String,
    /// 1-based line where the contract name is first referenced.
    pub line: usize,
}

/// A single contract node and the impl files that provably codegen it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NodeAnchor {
    /// The contract [`Contract::node_id`] this anchors.
    pub node_id: String,
    /// The node's kind (service / method / message).
    pub kind: ContractKind,
    /// Distinct languages whose codegen anchored this node.
    pub langs: BTreeSet<String>,
    /// The anchoring impl files, deterministic order.
    pub files: Vec<AnchorFile>,
}

impl NodeAnchor {
    /// Provable cross-language contract: codegen on ≥2 distinct languages. Only
    /// these mint a [`crate::graph::EdgeKind::ContractDirected`] cross-language
    /// edge.
    pub fn is_cross_language(&self) -> bool {
        self.langs.len() >= 2
    }

    /// Codegen present on exactly one language side. The counterpart did not
    /// generate, so no cross-language edge is claimed (degrade `one-sided`).
    pub fn is_one_sided(&self) -> bool {
        self.langs.len() == 1
    }
}

/// The anchoring over a fixed impl-file universe: every contract node that had
/// at least one provable codegen footprint, keyed by node id.
#[derive(Debug, Clone, Default)]
pub struct ContractAnchoring {
    anchors: BTreeMap<String, NodeAnchor>,
}

impl ContractAnchoring {
    /// Anchor `contracts` against `impl_contents` (`path → source` for the
    /// non-IDL source universe). Pure: the caller owns all reads. A file
    /// anchors a node iff it carries a codegen banner *and* references the
    /// node's declared name as a whole token.
    pub fn build(contracts: &ContractSet, impl_contents: &BTreeMap<String, String>) -> Self {
        let mut anchoring = ContractAnchoring::default();
        // Pre-filter to genuine codegen files: banner present + a known source
        // language. Everything else can never anchor, so we skip it wholesale.
        let codegen_files: Vec<(&String, &String, &'static str)> = impl_contents
            .iter()
            .filter_map(|(path, src)| {
                let lang = crate::lang_for_path(path)?;
                if has_codegen_marker(src) {
                    Some((path, src, lang))
                } else {
                    None
                }
            })
            .collect();
        if codegen_files.is_empty() {
            return anchoring;
        }
        for c in contracts.contracts() {
            let node_id = c.node_id();
            for (path, src, lang) in &codegen_files {
                if let Some(line) = first_word_line(src, &c.name) {
                    let entry =
                        anchoring
                            .anchors
                            .entry(node_id.clone())
                            .or_insert_with(|| NodeAnchor {
                                node_id: node_id.clone(),
                                kind: c.kind,
                                langs: BTreeSet::new(),
                                files: Vec::new(),
                            });
                    entry.langs.insert((*lang).to_string());
                    entry.files.push(AnchorFile {
                        path: (*path).to_string(),
                        lang: (*lang).to_string(),
                        line,
                    });
                }
            }
        }
        for a in anchoring.anchors.values_mut() {
            a.files.sort();
            a.files.dedup();
        }
        anchoring
    }

    /// The anchor for a contract node id, if any impl file codegens it.
    pub fn anchor(&self, node_id: &str) -> Option<&NodeAnchor> {
        self.anchors.get(node_id)
    }

    /// True when the node is anchored by ≥2 languages (provable cross-language).
    pub fn is_cross_language(&self, node_id: &str) -> bool {
        self.anchors
            .get(node_id)
            .is_some_and(NodeAnchor::is_cross_language)
    }

    /// True when the node is anchored by exactly one language (one-sided).
    pub fn is_one_sided(&self, node_id: &str) -> bool {
        self.anchors
            .get(node_id)
            .is_some_and(NodeAnchor::is_one_sided)
    }

    /// All node anchors, deterministic order.
    pub fn anchors(&self) -> impl Iterator<Item = &NodeAnchor> {
        self.anchors.values()
    }

    /// Whether any node was anchored.
    pub fn is_empty(&self) -> bool {
        self.anchors.is_empty()
    }
}

/// Case-insensitive presence of any codegen banner. Cheap: one lowercased pass.
fn has_codegen_marker(src: &str) -> bool {
    // Only the head of a file carries the banner; cap the scan so a stray
    // "@generated" deep in a hand-written file's string literal cannot masquerade
    // as provenance. 4 KiB covers even verbose multi-line thrift/grpc headers.
    let head = &src[..src.len().min(4096)];
    let lower = head.to_ascii_lowercase();
    CODEGEN_MARKERS.iter().any(|m| lower.contains(m))
}

/// The 1-based line on which `word` first appears as a whole identifier token
/// (surrounded by non-identifier chars), or `None`. Whole-token matching keeps
/// `GetUser` from matching inside `GetUserProfile`.
fn first_word_line(src: &str, word: &str) -> Option<usize> {
    if word.is_empty() {
        return None;
    }
    for (i, line) in src.lines().enumerate() {
        if line_contains_word(line, word) {
            return Some(i + 1);
        }
    }
    None
}

/// Whole-identifier-token containment on a single line.
fn line_contains_word(line: &str, word: &str) -> bool {
    let bytes = line.as_bytes();
    let wb = word.as_bytes();
    let mut start = 0;
    while let Some(pos) = find_from(bytes, wb, start) {
        let before_ok = pos == 0 || !is_ident_byte(bytes[pos - 1]);
        let after = pos + wb.len();
        let after_ok = after >= bytes.len() || !is_ident_byte(bytes[after]);
        if before_ok && after_ok {
            return true;
        }
        start = pos + 1;
    }
    false
}

/// First index of `needle` in `hay` at or after `from` (byte search).
fn find_from(hay: &[u8], needle: &[u8], from: usize) -> Option<usize> {
    if needle.is_empty() || from + needle.len() > hay.len() {
        return None;
    }
    (from..=hay.len() - needle.len()).find(|&i| &hay[i..i + needle.len()] == needle)
}

/// A byte that may appear inside an identifier (so token boundaries are honest).
fn is_ident_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// Convenience: the contract nodes declared by a subset of IDL files (used to
/// seed `shuttle impact --contract` from the *changed* IDL files only).
pub fn nodes_declared_in<'a>(set: &'a ContractSet, files: &BTreeSet<String>) -> Vec<&'a Contract> {
    set.contracts()
        .iter()
        .filter(|c| files.contains(&c.path))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::ContractSet;

    fn contents(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
        pairs
            .iter()
            .map(|(p, c)| (p.to_string(), c.to_string()))
            .collect()
    }

    const USER_PROTO: &str = "\
package user.api;
message GetUserRequest { string id = 1; }
message GetUserResponse { string name = 1; }
service UserService {
  rpc GetUser (GetUserRequest) returns (GetUserResponse);
}
";

    #[test]
    fn cross_language_contract_anchors_both_sides() {
        let idl = contents(&[("api/user.proto", USER_PROTO)]);
        let set = ContractSet::build(&idl);
        // Go server stub + TS client stub, both with a real codegen banner and a
        // reference to the method name.
        let impls = contents(&[
            (
                "gen/user.pb.go",
                "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage userapi\nfunc GetUser() {}\n",
            ),
            (
                "web/user_client.ts",
                "// @generated by protoc-gen-ts_proto\nexport function GetUser() {}\n",
            ),
        ]);
        let anchoring = ContractAnchoring::build(&set, &impls);
        // The method node is provably cross-language.
        assert!(anchoring.is_cross_language("user.api.UserService.GetUser"));
        let a = anchoring.anchor("user.api.UserService.GetUser").unwrap();
        assert_eq!(
            a.langs,
            ["go", "typescript"].iter().map(|s| s.to_string()).collect()
        );
        assert_eq!(a.files.len(), 2);
    }

    #[test]
    fn a4_bare_name_without_codegen_marker_never_anchors() {
        // The A4 病根: Go helper() and Python helper() share a name but neither is
        // codegen. Even if a contract *declared* `helper`, no banner ⇒ no anchor.
        let idl = contents(&[(
            "api/util.proto",
            "package util;\nservice Util { rpc helper (Empty) returns (Empty); }\nmessage Empty {}\n",
        )]);
        let set = ContractSet::build(&idl);
        let impls = contents(&[
            ("go/util.go", "package util\nfunc helper() {}\n"),
            ("py/util.py", "def helper():\n    pass\n"),
        ]);
        let anchoring = ContractAnchoring::build(&set, &impls);
        assert!(
            anchoring.is_empty(),
            "no banner ⇒ no cross-language edge (A4)"
        );
        assert!(!anchoring.is_cross_language("util.Util.helper"));
    }

    #[test]
    fn one_sided_codegen_is_not_cross_language() {
        let idl = contents(&[("api/user.proto", USER_PROTO)]);
        let set = ContractSet::build(&idl);
        // Only the Go side generated; the TS client was never regenerated.
        let impls = contents(&[(
            "gen/user.pb.go",
            "// Code generated by protoc-gen-go. DO NOT EDIT.\nfunc GetUser() {}\n",
        )]);
        let anchoring = ContractAnchoring::build(&set, &impls);
        assert!(anchoring.is_one_sided("user.api.UserService.GetUser"));
        assert!(!anchoring.is_cross_language("user.api.UserService.GetUser"));
    }

    #[test]
    fn stale_contract_declared_but_no_codegen_footprint() {
        let idl = contents(&[("api/user.proto", USER_PROTO)]);
        let set = ContractSet::build(&idl);
        // A hand-written file references GetUser but carries NO codegen banner:
        // it does not prove codegen, so the node stays unanchored (stale).
        let impls = contents(&[(
            "app/handwritten.go",
            "package app\n// calls GetUser somewhere\n",
        )]);
        let anchoring = ContractAnchoring::build(&set, &impls);
        assert!(anchoring.anchor("user.api.UserService.GetUser").is_none());
    }

    #[test]
    fn whole_token_match_only() {
        let idl = contents(&[(
            "api/u.proto",
            "package u;\nservice S { rpc GetUser (R) returns (R); }\nmessage R {}\n",
        )]);
        let set = ContractSet::build(&idl);
        // `GetUserProfile` must NOT anchor `GetUser` — different identifier.
        let impls = contents(&[(
            "gen/x.go",
            "// Code generated by protoc-gen-go. DO NOT EDIT.\nfunc GetUserProfile() {}\n",
        )]);
        let anchoring = ContractAnchoring::build(&set, &impls);
        assert!(anchoring.anchor("u.S.GetUser").is_none());
    }

    #[test]
    fn message_node_anchors_across_languages() {
        let idl = contents(&[("api/user.proto", USER_PROTO)]);
        let set = ContractSet::build(&idl);
        let impls = contents(&[
            (
                "gen/user.pb.go",
                "// Code generated by protoc-gen-go. DO NOT EDIT.\ntype GetUserRequest struct {}\n",
            ),
            (
                "web/models.ts",
                "// @generated\nexport interface GetUserRequest {}\n",
            ),
        ]);
        let anchoring = ContractAnchoring::build(&set, &impls);
        assert!(anchoring.is_cross_language("user.api.GetUserRequest"));
    }

    #[test]
    fn nodes_declared_in_filters_by_changed_file() {
        let idl = contents(&[
            ("api/user.proto", USER_PROTO),
            ("api/other.proto", "package other;\nmessage Ping {}\n"),
        ]);
        let set = ContractSet::build(&idl);
        let changed: BTreeSet<String> = ["api/user.proto".to_string()].into_iter().collect();
        let decl = nodes_declared_in(&set, &changed);
        assert!(decl.iter().all(|c| c.path == "api/user.proto"));
        assert!(decl.iter().any(|c| c.name == "GetUser"));
        assert!(!decl.iter().any(|c| c.name == "Ping"));
    }
}
